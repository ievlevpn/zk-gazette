#!/usr/bin/env python3
"""
Example drop-in Gazette source: emits a `kind: "custom"` tab with paginated cards.

Copy this file to a name without a leading underscore (e.g. `digest_tab.py`)
to enable it automatically in `generate.py`.
"""

from __future__ import annotations

import json


def card(kicker: str, title: str, body: str, badge: str = "") -> dict:
    header_children = [{"kind": "text", "text": kicker, "style": "label", "caps": True}]
    if badge:
        header_children.append({"kind": "pill", "text": badge, "width": "14%", "tone": "ink"})
    return {
        "kind": "box",
        "border": "thin",
        "pad": "medium",
        "radius": "small",
        "child": {
            "kind": "column",
            "gap": "xsmall",
            "children": [
                {"kind": "row", "align": "center", "gap": "small", "children": header_children},
                {"kind": "text", "text": title, "font": "serif", "weight": "bold", "size": "large"},
                {"kind": "text", "text": body, "font": "serif", "size": "body"},
            ],
        },
    }


def main() -> None:
    # Important: put each card directly in `blocks` (not wrapped in one outer `column`)
    # so Gazette's multi-page e-ink layout can paginate cleanly between cards.
    payload = {
        "tabs": [
            {
                "id": "desk",
                "title": "Desk",
                "kind": "custom",
                "blocks": [
                    {"kind": "text", "text": "CUSTOM DESK · GENERATED BY SOURCES/", "style": "label", "caps": True},
                    card(
                        "EXAMPLE CARD",
                        "Build any custom e-ink section",
                        "Custom tabs render native GazetteNode trees (rows, columns, bordered boxes, pills, dividers, quotes, and tappable links to articles or other tabs).",
                        badge="NEW",
                    ),
                    card(
                        "IDEAS",
                        "What you can drop into generator/sources/",
                        "ArXiv paper watches, GitHub release radars, language flashcards, city transit alerts, sports standings, or daily book excerpts.",
                    ),
                ],
            }
        ]
    }
    print(json.dumps(payload, ensure_ascii=False))


if __name__ == "__main__":
    main()
